"""Run the curated edit/chat/routing test set against the REAL model and write measured results.

    cd backend
    python -X utf8 -I tools/eval_edits.py                 # all cases  -> docs/eval_results.json + docs/EVAL_RESULTS.md
    python -X utf8 -I tools/eval_edits.py --only docx-retitle,chat-greeting
    python -X utf8 -I tools/eval_edits.py --report-only   # rebuild the markdown from the saved json

Uses the same LangGraph workflow, LLM provider (timeouts, retries, token governor) and tracing as the API, but no
database or HTTP layer. Needs GROQ_API_KEY. Groq's free tier caps a model at 8,000 tokens/minute, so a full run
takes a while: the governor paces the calls instead of failing.
"""
import argparse
import datetime as dt
import json
import shutil
import sys
import tempfile
import time
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
ROOT = BACKEND.parent
sys.path.insert(0, str(BACKEND))

from langgraph.checkpoint.memory import MemorySaver  # noqa: E402

from app.core.config import get_settings  # noqa: E402
from app.llm.provider import GroqLLM  # noqa: E402
from app.observability.trace import RunTrace, use_trace  # noqa: E402
from app.services.storage import LocalStorage  # noqa: E402
from app.workflows.graph import Deps, build_graph  # noqa: E402
from tests.eval.edit_cases import CASES  # noqa: E402
from tests.eval.grade import grade_case, percentile, summarize  # noqa: E402

OUT_JSON, OUT_MD = ROOT / "docs" / "eval_results.json", ROOT / "docs" / "EVAL_RESULTS.md"
RUN1 = ROOT / "docs" / "eval_results_run1_before_fixes.json"


def run_case(case: dict, llm, tmp: Path) -> tuple[dict, dict]:
    storage = LocalStorage(tmp / "store")
    sid = "eval-" + case["id"]
    files = []
    for i, rel in enumerate(case["files"]):
        src = ROOT / "sample_templates" / rel
        path, _ = storage.save_upload(sid, src.read_bytes(), src.suffix.lstrip("."))
        files.append({"id": f"f{i}", "name": src.name, "path": storage.rel(path), "format": src.suffix.lstrip("."), "kind": "upload"})
    graph = build_graph(Deps(llm, storage), checkpointer=MemorySaver())
    trace, t0, error = RunTrace(sid), time.perf_counter(), ""
    state: dict = {}
    try:
        with use_trace(trace):
            state = graph.invoke({"session_id": sid, "user_message": case["msg"], "history": [], "files": files},
                                 {"configurable": {"thread_id": sid}})
    except Exception as e:  # noqa: BLE001 - a crash is a result, not a reason to abort the whole eval
        error = f"{type(e).__name__}: {str(e)[:200]}"
    dur = (time.perf_counter() - t0) * 1000
    art = state.get("artifact")
    produced = storage.resolve(art["path"]) if art else None
    status = "error" if (error or state.get("error")) else ("gave_up" if state.get("intent") == "edit" and not art and not state.get("declined") else "ok")
    row = grade_case(case, state.get("intent", "crash"), produced, status)
    tot = trace.totals()
    render = state.get("render") or {}
    row.update(msg=case["msg"], attempts=state.get("attempts", 0), preserved=bool(render.get("preserved")) if art else None,
               violations=render.get("violations", []), duration_ms=round(dur, 1), input_tokens=tot["input_tokens"],
               output_tokens=tot["output_tokens"], cost_usd=tot["cost_usd"], llm_calls=tot["llm_calls"],
               llm_failures=tot["llm_failures"], llm_retries=tot["llm_retries"], crash=error,
               reply=(state.get("response") or "")[:240],
               plan_ops=[o.get("op") for o in (state.get("plan") or {}).get("ops", [])],
               stages_ms={s["name"]: s["duration_ms"] for s in trace.to_dict()["spans"] if s["kind"] == "node"})
    return row, trace.to_dict(dur)


def pct(x):
    return "n/a" if x is None else f"{x * 100:.0f}%"


def render_md(data: dict) -> str:
    s, rows, meta = data["summary"], data["rows"], data["meta"]

    def r(k):
        v = s[k]
        return f"{v['pass']}/{v['n']} ({pct(v['rate'])})"
    lat, tok, cost = s["latency_all"], s["tokens"], s["cost_usd"]
    out = [
        "# Evaluation results (generated; do not edit by hand)",
        "",
        f"Generated by `backend/tools/eval_edits.py` on {meta['date']} against **{meta['model']}** (reasoning effort low, temperature 0). "
        f"Cases: `backend/tests/eval/edit_cases.py` ({s['cases']} cases over the demo DOCX/PPTX/XLSX templates). "
        "A case passes only if the **produced file** satisfies every check (target changed, text that should be gone is gone, "
        "untouched content survived) - the chat reply is never used as evidence. One run, no cherry-picking: every case is listed below. "
        "LLM output is not deterministic, so a re-run can differ by a case or two.",
        "",
        "## Headline",
        "",
        "| Metric | Result |",
        "|---|---|",
        f"| Task success, all cases | {r('task_success')} |",
        f"| Task success, edit requests | {r('edit_task_success')} |",
        f"| Routing accuracy (chat / edit / clarify) | {r('routing_accuracy')} |",
        f"| Edit plan valid on the first attempt | {r('edit_first_try_valid')} |",
        f"| Edit plan valid after validator-feedback retries | {r('edit_eventually_valid')} |",
        f"| Design preserved (preservation check) on produced files | {r('edit_preservation')} |",
        f"| Content correct on produced files | {r('edit_content_correct')} |",
        f"| Mean planning attempts per produced edit | {s['mean_attempts_when_edited']} |",
        "",
        "## Performance (same run)",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| End-to-end latency p50 / p95 / max | {lat['p50_s']} s / {lat['p95_s']} s / {lat['max_s']} s |",
        f"| Mean LLM calls per request | {tok['mean_llm_calls']} |",
        f"| Mean tokens per request (in / out) | {tok['mean_input']} / {tok['mean_output']} |",
        f"| Total tokens (in / out) | {tok['total_input']} / {tok['total_output']} |",
        f"| Cost per request (mean) | ${cost['mean_per_request']:.5f} |",
        f"| Cost per edit request (mean) | {'n/a' if cost['mean_per_edit'] is None else '$%.5f' % cost['mean_per_edit']} |",
        f"| Total cost of this run | ${cost['total']:.5f} |",
        f"| LLM call failures / retries | {s['llm_failures']} / {s['llm_retries']} |",
        "",
        f"Cost = tokens x list price (${meta['price_in']}/1M input, ${meta['price_out']}/1M output, Groq console, "
        "checked 2026-11-17). Latency includes the token governor's pacing waits (Groq free tier: 8,000 tokens/min), so it "
        "measures this deployment's real behaviour, not the model's raw speed.",
        "",
        "Failed model calls report no usage, so a request whose calls all failed shows 0 tokens (the `no_edit` cases below); "
        "tokens and cost are therefore a slight undercount.",
        "",
        "### Latency by kind of request",
        "",
        "| Kind | n | p50 | p95 | mean |",
        "|---|---|---|---|---|",
    ]
    for k, v in s["latency_by_expectation"].items():
        out.append(f"| {k} | {v['n']} | {v['p50_s']} s | {v['p95_s']} s | {v['mean_s']} s |")
    waits = {i: sum(sp["attrs"].get("rate_wait_s") or 0 for sp in tr["spans"]) for i, tr in data.get("traces", {}).items()}
    active = [(x["duration_ms"] / 1000) - waits.get(x["id"], 0) for x in rows]
    n_paced = sum(1 for w in waits.values() if w > 1)
    out += ["", "### Model time vs. rate-limit waiting", "",
            f"{n_paced} of {len(rows)} requests spent more than 1 s waiting in the token governor "
            f"(total {sum(waits.values()):.0f} s of the {sum(x['duration_ms'] for x in rows) / 1000:.0f} s run). The cases run back to back with no "
            "think time, which is the worst case for an 8,000 tokens/min quota; a person typing hits it far less often. Latency with the waits removed:", "",
            "| | p50 | p95 | max |", "|---|---|---|---|",
            f"| as measured (includes waits) | {lat['p50_s']} s | {lat['p95_s']} s | {lat['max_s']} s |",
            f"| model + processing only | {percentile(active, 50):.2f} s | {percentile(active, 95):.2f} s | {max(active):.2f} s |"]
    stage: dict[str, list[float]] = {}
    for tr in data.get("traces", {}).values():
        for sp in tr["spans"]:
            key = {"node": sp["name"], "llm": "(LLM call)", "tool": sp["name"]}[sp["kind"]]
            stage.setdefault(f"{sp['kind']}:{key}", []).append(sp["duration_ms"] / 1000)
    out += ["", "### Where the time goes (all spans from the traces)", "",
            "| Span | Count | Mean | p95 | Max |", "|---|---|---|---|---|"]
    for k, v in sorted(stage.items(), key=lambda kv: -sum(kv[1])):
        out.append(f"| {k} | {len(v)} | {sum(v) / len(v):.2f} s | {percentile(v, 95):.2f} s | {max(v):.2f} s |")
    out += ["", "`node:` spans are LangGraph steps (they include the LLM calls made inside them); `llm:` spans are single model "
            "requests; `tool:` spans are search / retrieval calls. Deterministic steps (understand, validate, render, respond) "
            "are milliseconds; time is dominated by the model and by rate-limit pacing.", "",
            "## Every case", "",
            "| Case | Expected | Got | Pass | Attempts | Preserved | Checks | Latency | Tokens in/out | Cost |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for x in rows:
        chk = ", ".join(f"{k}:{'ok' if v else 'FAIL'}" for k, v in x["checks"].items()) or "-"
        pres = "-" if x["preserved"] is None else ("yes" if x["preserved"] else "NO")
        out.append(f"| {x['id']} | {x['expect']} | {x['intent']} | {'PASS' if x['success'] else '**FAIL**'} | {x['attempts']} | {pres} | "
                   f"{chk} | {x['duration_ms'] / 1000:.1f} s | {x['input_tokens']}/{x['output_tokens']} | ${x['cost_usd']:.5f} |")
    if RUN1.exists():
        r1 = json.loads(RUN1.read_text(encoding="utf-8"))
        a, b = r1["summary"], s
        out += ["", "## Run history: first run (before fixes) vs this run", "",
                "The first run's traces exposed two defects (raw provider error text shown to the user; each retry after a rejected "
                "structured call stalled ~50 s because the failed call kept its full token reservation) and one routing miss (an ambiguous "
                "request with two candidate files was edited instead of clarified). They were fixed, then everything was re-run. "
                "Both runs are single samples of a non-deterministic model.", "",
                "| Metric | First run | This run |", "|---|---|---|"]
        for label, key in (("Task success, all", "task_success"), ("Routing accuracy", "routing_accuracy"),
                           ("First-try valid edits", "edit_first_try_valid")):
            out.append(f"| {label} | {pct(a[key]['rate'])} ({a[key]['pass']}/{a[key]['n']}) | {pct(b[key]['rate'])} ({b[key]['pass']}/{b[key]['n']}) |")
        by1 = {x["id"]: x for x in r1["rows"]}
        out.append(f"| Slowest request | {a['latency_all']['max_s']} s | {b['latency_all']['max_s']} s |")
        for x in rows:
            y = by1.get(x["id"])
            if y and (y["success"] != x["success"] or abs(y["duration_ms"] - x["duration_ms"]) > 20000 and x["expect"] == "no_edit"):
                out.append(f"| `{x['id']}` | {'PASS' if y['success'] else 'FAIL'}, {y['duration_ms'] / 1000:.0f} s | {'PASS' if x['success'] else 'FAIL'}, {x['duration_ms'] / 1000:.0f} s |")
    fails = [x for x in rows if not x["success"]]
    out += ["", "## Failures", ""]
    if not fails:
        out.append("None in this run.")
    for x in fails:
        out += [f"- **{x['id']}** ({x['expect']} -> got `{x['intent']}`, status `{x['status']}`): \"{x['msg']}\"",
                f"  - checks: {x['checks'] or 'no file produced'}; violations: {x['violations'] or 'none'}; ops: {x['plan_ops'] or 'none'}",
                f"  - reply: {x['reply']!r}" + (f"; crash: {x['crash']}" if x['crash'] else "")]
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--report-only", action="store_true")
    a = ap.parse_args()
    if a.report_only:
        OUT_MD.write_text(render_md(json.loads(OUT_JSON.read_text(encoding="utf-8"))), encoding="utf-8")
        print("wrote", OUT_MD)
        return 0
    cases = [c for c in CASES if not a.only or c["id"] in a.only.split(",")]
    st = get_settings()
    llm = GroqLLM()
    rows, traces = [], {}
    tmp = Path(tempfile.mkdtemp(prefix="documind-eval-"))
    try:
        for i, c in enumerate(cases, 1):
            row, tr = run_case(c, llm, tmp)
            rows.append(row)
            traces[c["id"]] = tr
            print(f"[{i}/{len(cases)}] {c['id']:<22} {'PASS' if row['success'] else 'FAIL'}  intent={row['intent']:<8} attempts={row['attempts']} "
                  f"{row['duration_ms'] / 1000:5.1f}s  tok={row['input_tokens']}/{row['output_tokens']}", flush=True)
            data = {"meta": {"date": dt.date.today().isoformat(), "model": st.groq_model, "price_in": st.price_input_per_mtok,
                             "price_out": st.price_output_per_mtok},
                    "summary": summarize(rows), "rows": rows, "traces": traces}
            OUT_JSON.write_text(json.dumps(data, indent=1, ensure_ascii=False), encoding="utf-8")  # incremental: survive a crash
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    OUT_MD.write_text(render_md(data), encoding="utf-8")
    print(json.dumps(data["summary"], indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
